import { expect, test } from '@playwright/test'
import AxeBuilder from '@axe-core/playwright'
import { mockQuranContent } from './content-fixture'

test('search and verse navigation fit a narrow screen and work by keyboard', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 640 })
  await mockQuranContent(page)
  await page.goto('./quran/')
  await page.getByRole('button', { name: 'Search', exact: true }).focus()
  await page.keyboard.press('Enter')
  await expect(page.getByRole('heading', { name: 'Search', exact: true })).toBeFocused()
  const heading = await page.getByRole('heading', { name: 'Search', exact: true }).boundingBox()
  const searchNavigation = await page.getByRole('navigation', { name: 'Reader controls' }).boundingBox()
  if (!heading || !searchNavigation) throw new Error('Search heading and navigation must be visible')
  expect(heading.y).toBeGreaterThanOrEqual(searchNavigation.y + searchNavigation.height)
  const search = page.getByRole('textbox', { name: 'Search the Quran' })
  await search.fill('1:3')
  await search.press('Enter')
  const verse = page.getByRole('article').filter({ hasText: '1:3' })
  await expect(verse).toBeFocused()
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= document.documentElement.clientWidth)).toBe(true)
  const position = await verse.boundingBox()
  const navigation = await page.getByRole('navigation', { name: 'Reader controls' }).boundingBox()
  if (!position || !navigation) throw new Error('Verse and navigation must be visible')
  expect(position.y).toBeGreaterThanOrEqual(navigation.y + navigation.height)
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  await expect(search).toHaveValue('1:3')
  expect((await new AxeBuilder({ page }).analyze()).violations).toEqual([])
  await page.reload()
  await expect(page.getByRole('button', { name: 'Read', pressed: true })).toBeVisible()
})

test('positions a long unloaded verse below navigation', async ({ page }) => {
  await page.setViewportSize({ width: 320, height: 640 })
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await mockQuranContent(page)
  await page.route('**/functions/v1/quran/v2/verses?*', route => {
    const params = new URL(route.request().url()).searchParams
    if (params.get('chapter') !== '2') return route.fallback()
    return route.fulfill({ json: { verses: [{ number: 255, arabic: 'نص '.repeat(200), translationHtml: 'Translation '.repeat(200) }], translationName: 'Translator', nextPage: null } })
  })
  await page.goto('./quran/')
  await page.getByRole('button', { name: 'Search', exact: true }).click()
  await page.getByRole('textbox', { name: 'Search the Quran' }).fill('2:255')
  await page.getByRole('button', { name: 'Search Quran' }).click()
  const verse = page.getByRole('article').filter({ hasText: '2:255' })
  await expect(verse).toBeFocused()
  const position = await verse.boundingBox()
  const navigation = await page.getByRole('navigation', { name: 'Reader controls' }).boundingBox()
  if (!position || !navigation) throw new Error('Verse and navigation must be visible')
  expect(position.y).toBeGreaterThanOrEqual(navigation.y + navigation.height)
})

